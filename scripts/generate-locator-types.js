#!/usr/bin/env node
/**
 * CLI wrapper for the locator-name codegen (src/codegen/generateLocatorTypes.ts) -
 * standalone plain JS so it runs under plain `node`, without a TS loader,
 * exactly like postinstall.js. Scans the current project's locator YAML
 * files and writes e2e/locators/generated/locator-names.d.ts.
 *
 * Usage (from a consumer project): npx playwright-without-bdd-generate-types
 */
const fs = require('fs');
const path = require('path');
const yaml = require('js-yaml');

const root = process.cwd();
const locatorRoot = path.join(root, 'e2e', 'locators', 'generated');
const categories = ['web', 'api', 'endtoend'];

function collectNames(fp) {
  try {
    const raw = fs.readFileSync(fp, 'utf8');
    const doc = fp.endsWith('.json') ? JSON.parse(raw) : yaml.load(raw);
    if (!doc || typeof doc !== 'object' || Array.isArray(doc)) return [];
    return Object.keys(doc);
  } catch {
    return [];
  }
}

function walk(dir, files) {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, files);
    else if (entry.name.endsWith('.yaml') || entry.name.endsWith('.json')) files.push(full);
  }
}

const files = [];
for (const cat of categories) walk(path.join(locatorRoot, cat), files);
const commonFile = path.join(root, 'e2e', 'locators', 'common.yaml');
if (fs.existsSync(commonFile)) files.push(commonFile);

const names = new Set();
for (const fp of files) collectNames(fp).forEach((n) => names.add(n));
const sorted = [...names].sort();

const union = sorted.length > 0 ? sorted.map((n) => `  | ${JSON.stringify(n)}`).join('\n') : '  | never';
const outFile = path.join(locatorRoot, 'locator-names.d.ts');
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(
  outFile,
  `// Auto-generated by playwright-without-bdd-library. Do not edit by hand -\n` +
    `// re-run \`npx playwright-without-bdd-generate-types\` after changing locator YAML files.\nexport type LocatorName =\n${union};\n`,
  'utf8',
);
console.log(`[playwright-without-bdd-library] wrote ${sorted.length} locator name(s) to ${path.relative(root, outFile)}`);
